"""JSON Schema exports for every format the toolkit reads or writes.

The point of exporting these is adoption without dependency: a GRC platform, a spreadsheet macro
or a Go service can validate an AI inventory register, a materiality assessment or a vendor
assessment against the same schema the library enforces, without installing Python.

The files live in ``schemas/`` at the repository root and are regenerated by ``airm schemas``
(or ``make schemas``). A test asserts the committed files match the models, so a schema cannot
drift from the code that produces it.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING, Any

from airm import __version__
from airm.controls import Control, ControlCatalogue, InstitutionReport, UseCaseReport
from airm.crosswalk import Crosswalk, Mapping
from airm.evals import EvalResult, ToolScopeAudit
from airm.evals.probes import ProbeSuiteResult
from airm.inventory import AgentExtension, Register, UseCase
from airm.materiality import Assessment, PortfolioAssessment, Rubric
from airm.monitor import Incident, Record
from airm.scan import ScanReport
from airm.thirdparty import VendorAssessment, VendorRegister

if TYPE_CHECKING:
    from pydantic import BaseModel

# File stem to the model it describes, with the MAS paragraphs the format serves. The stems are
# part of the published interface: other tools reference them by URL.
EXPORTS: dict[str, tuple[type[BaseModel], str]] = {
    "ai-inventory-register": (Register, "MAS-AIRM §4.5-§4.9"),
    "ai-use-case": (UseCase, "MAS-AIRM §4.7, fn24"),
    "agent-extension": (AgentExtension, "MAS-AIRM §4.8 fn25, §5.16, §5.23(a)"),
    "materiality-rubric": (Rubric, "MAS-AIRM §4.10-§4.12"),
    "materiality-assessment": (Assessment, "MAS-AIRM §4.10-§4.13"),
    "portfolio-assessment": (PortfolioAssessment, "MAS-AIRM §3.4, §4.11"),
    "control": (Control, "MAS-AIRM §5.1-§5.26"),
    "control-catalogue": (ControlCatalogue, "MAS-AIRM §5.2"),
    "use-case-control-report": (UseCaseReport, "MAS-AIRM §5.2, §5.18"),
    "institution-control-report": (InstitutionReport, "MAS-AIRM §3.3-§3.5, §4.1-§4.4"),
    "audit-trail-record": (Record, "MAS-AIRM §5.23(d), §5.17"),
    "incident": (Incident, "MAS-AIRM §5.23(b), fn20"),
    "shadow-ai-scan-report": (ScanReport, "MAS-AIRM §4.4 fn22, §4.2 fn21"),
    "eval-result": (EvalResult, "MAS-AIRM §5.14-§5.15, fn46"),
    "guardrail-probe-suite-result": (ProbeSuiteResult, "MAS-AIRM §5.15 fn46"),
    "tool-scope-audit": (ToolScopeAudit, "MAS-AIRM §5.16, §5.23(a)"),
    "vendor-assessment": (VendorAssessment, "MAS-AIRM §5.10-§5.11"),
    "vendor-register": (VendorRegister, "MAS-AIRM §5.10-§5.11"),
    "crosswalk-mapping": (Mapping, "MAS-AIRM Annex-style crosswalk"),
    "crosswalk": (Crosswalk, "MAS-AIRM to ISO 42001 / NIST AI RMF / EU AI Act"),
}

BASE_URL = "https://raw.githubusercontent.com/thanatchon36/airmkit/main/schemas"

DISCLAIMER = (
    "Independent open-source project, not affiliated with or endorsed by the Monetary Authority "
    "of Singapore. Field semantics are the authors' interpretation of the Guidelines on "
    "Artificial Intelligence Risk Management (7 October 2026), not a MAS specification."
)


def schema_for(stem: str) -> dict[str, Any]:
    """Return the JSON Schema for one exported format.

    Args:
        stem: A key of :data:`EXPORTS`, e.g. ``"ai-inventory-register"``.

    Returns:
        The schema, with ``$id``, ``$schema``, the clauses it serves and the disclaimer added.

    Raises:
        KeyError: If the stem names no exported format.
    """
    if stem not in EXPORTS:
        raise KeyError(f"unknown schema {stem!r}; known: {', '.join(sorted(EXPORTS))}")
    model, clauses = EXPORTS[stem]
    schema = model.model_json_schema(mode="validation")
    ordered: dict[str, Any] = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"{BASE_URL}/{stem}.schema.json",
        "x-airmkit-version": __version__,
        "x-mas-airm-clauses": clauses,
        "x-disclaimer": DISCLAIMER,
    }
    ordered.update(schema)
    return ordered


def export(out_dir: str | Path) -> dict[str, Path]:
    """Write every JSON Schema to a directory.

    Args:
        out_dir: Destination, created if needed.

    Returns:
        File stem to the path written.
    """
    target = Path(out_dir)
    target.mkdir(parents=True, exist_ok=True)
    written: dict[str, Path] = {}
    for stem in EXPORTS:
        path = target / f"{stem}.schema.json"
        path.write_text(
            json.dumps(schema_for(stem), indent=2, sort_keys=False) + "\n", encoding="utf-8"
        )
        written[stem] = path
    index = target / "README.md"
    index.write_text(_index_markdown(), encoding="utf-8")
    written["README"] = index
    return written


def _index_markdown() -> str:
    """Return the schema directory's index, generated so it cannot drift from EXPORTS."""
    out = [
        "# JSON Schemas",
        "",
        "Generated by `airm schemas` (or `make schemas`) from the Pydantic models in "
        "`src/airm/`. Do not edit by hand; a test asserts these files match the models.",
        "",
        f"> {DISCLAIMER}",
        "",
        "| Schema | Model | MAS-AIRM clauses |",
        "|---|---|---|",
    ]
    out.extend(
        f"| [`{stem}.schema.json`]({stem}.schema.json) | `{model.__module__}.{model.__name__}` "
        f"| {clauses} |"
        for stem, (model, clauses) in EXPORTS.items()
    )
    out.append("")
    out.append(
        "Validate a register with any JSON Schema tool, for example "
        "`check-jsonschema --schemafile schemas/ai-inventory-register.schema.json "
        "ai-inventory.yaml`."
    )
    out.append("")
    return "\n".join(out)
