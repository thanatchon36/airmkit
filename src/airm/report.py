"""Audit-ready pack generation.

Produces the artefacts a reviewer, internal auditor or supervisor actually asks for:

* **AI inventory register** (MAS-AIRM §4.5-§4.9), with completeness gaps named.
* **Risk materiality report** (§4.10-§4.13), with every score's reasons.
* **Control applicability statement** (§5.2), in the style of an ISO statement of applicability:
  which controls apply, which do not and why not.
* **Gap analysis by effective date** (§1.8), separating what is due 7 October 2027 from what is
  due 7 October 2028.
* **Board and senior management one-pager** (§3.4, §3.5(f)).
* **Clause index**, generated from the catalogue so it can never drift from it.

Output is Markdown first, because Markdown diffs in version control and an auditor can read it
without a licence. DOCX is produced from the Markdown when ``python-docx`` is installed, and PDF
is left to pandoc via ``make``: a toolkit that bundles a PDF engine is a toolkit nobody can
install.
"""

